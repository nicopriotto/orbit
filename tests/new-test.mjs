async function open(viewport) {
  const page = await (await browser.newContext({ viewport })).newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.exposeFunction('stubParts', () => ({ front, back }));
  await page.addInitScript(() => {
    window.__posts = [];
    const real = window.fetch;
    window.fetch = async (url, options) => {
      if (!String(url).includes('api/try-on')) return real(url, options);
      window.__posts.push(url);
      const parts = await window.stubParts();
      const enc = (o) => new TextEncoder().encode(`${JSON.stringify(o)}\n`);
      return new Response(new ReadableStream({ start(c) { c.enqueue(enc({ front: parts.front })); c.enqueue(enc({ back: parts.back })); c.close(); } }));
    };
  });
  const posts = [];
  await page.route('**/api/looks', (route) => { if (route.request().method() === 'POST') { posts.push(1); return setTimeout(() => route.fulfill({ status: 502, contentType: 'application/json', body: '{"error":"stub"}' }), 250); } return route.continue(); });
  await page.goto('http://localhost:5192/', { waitUntil: 'networkidle' });
  await page.waitForTimeout(900);
  return { page, errors, posts };
}
