import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
const require = createRequire('/Users/nicolaspriotto/proyects/clothes/hackathon-meta/video/x.js');
const { chromium } = require('playwright');
const HERE = '/private/tmp/claude-501/-Users-nicolaspriotto-proyects-clothes/09261622-20ca-4ae3-9e14-0267aed9fc8a/scratchpad';
const PHOTO = '/Users/nicolaspriotto/proyects/clothes/hackathon-meta/modelo-demo.jpg';
const front = readFileSync(`${HERE}/tryon/dress-black-none-front.webp`).toString('base64');
const back = readFileSync(`${HERE}/tryon/dress-black-none-back.webp`).toString('base64');
const browser = await chromium.launch();
for (const [name, viewport] of [['wide', { width: 1440, height: 806 }], ['phone', { width: 390, height: 844 }]]) {
  const page = await (await browser.newContext({ viewport })).newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.exposeFunction('parts', () => ({ front, back }));
  await page.addInitScript(() => {
    window.__posts = 0;
    const real = window.fetch;
    window.fetch = async (url, options) => {
      if (!String(url).includes('api/try-on')) return real(url, options);
      window.__posts += 1;
      const p = await window.parts();
      const enc = (o) => new TextEncoder().encode(`${JSON.stringify(o)}\n`);
      return new Response(new ReadableStream({ start(c) { c.enqueue(enc({ front: p.front })); c.enqueue(enc({ back: p.back })); c.close(); } }));
    };
  });
  await page.route('**/api/looks', (r) => (r.request().method() === 'POST' ? r.abort() : r.continue()));
  await page.goto('http://localhost:5192/', { waitUntil: 'networkidle' });
  await page.waitForTimeout(800);
  await page.click('#try');
  await page.setInputFiles('#upload-file', PHOTO);
  await page.waitForFunction(() => !document.getElementById('upload-preview').hidden);
  await page.check('#upload-consent');
  await page.click('#upload-send');
  await page.waitForFunction(() => !document.getElementById('leave').hidden);
  await page.waitForTimeout(2500);
  const onWorn = await page.locator('#change-photo').isVisible();
  await page.screenshot({ path: `${HERE}/views/photo-${name}-worn.png` });
  await page.click('#leave');
  await page.waitForTimeout(800);
  const onMannequin = await page.locator('#change-photo').isVisible();
  await page.screenshot({ path: `${HERE}/views/photo-${name}-mannequin.png` });
  await page.click('#try');
  await page.waitForTimeout(800);
  const noDialog = !(await page.locator('#upload').evaluate((d) => d.open));
  const posts1 = await page.evaluate(() => window.__posts);
  await page.waitForTimeout(600);
  await page.click('#change-photo');
  await page.waitForTimeout(400);
  const dialog = await page.locator('#upload').evaluate((d) => d.open);
  await page.click('#upload-send');
  await page.waitForTimeout(800);
  const samePhotoNoSpend = (await page.evaluate(() => window.__posts)) === posts1;
  await page.click('#change-photo');
  await page.waitForTimeout(300);
  await page.setInputFiles('#upload-file', `${HERE}/otra-foto.jpg`);
  await page.waitForTimeout(500);
  await page.click('#upload-send');
  await page.waitForTimeout(1800);
  console.log(name, { onWorn, onMannequin, retryNoDialog: noDialog, posts1, dialog, samePhotoNoSpend, newPhotoCalls: await page.evaluate(() => window.__posts), errors });
  await page.close();
}
await browser.close();
